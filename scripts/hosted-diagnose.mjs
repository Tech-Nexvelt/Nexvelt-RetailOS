// READ-ONLY diagnosis of which RetailOS migrations are present in a database. Runs ONE read-only transaction that is always
// rolled back. It applies nothing, records nothing, creates/alters/drops nothing, and never bypasses the fresh-project guard.
//   node scripts/hosted-diagnose.mjs                 diagnose the database in RETAILOS_DATABASE_URL (TLS verified; no token, no API)
//   node scripts/hosted-diagnose.mjs --emit-sql      (re)write supabase/retailos/diagnostics/diagnose.sql for manual review/running
// Prints catalogue facts and counts only: no passwords, no connection string, no business data.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import pg from "pg";
import { diagnosticSql, expectedObjects, functionCompareSql, lastDefiningMigration, summarySql, verdicts } from "./lib/diagnose-core.mjs";

const root = join(import.meta.dirname, "..");
const migDir = join(root, "supabase", "retailos", "migrations");
const diagDir = join(root, "supabase", "retailos", "diagnostics");
const objs = expectedObjects(migDir);
const migFiles = readdirSync(migDir).filter((f) => f.endsWith(".sql")).sort();
const migs = migFiles.map((f) => f.slice(0, 14));
const hashLines = readFileSync(join(diagDir, "expected_function_hashes.txt"), "utf8").trim().split("\n");

const HISTORY_SQL = `select to_regclass('supabase_migrations.schema_migrations') is not null as history_table_exists`;
const XMIN_SQL = `select c.xmin::text as creating_transaction, count(*) as tables, string_agg(c.relname, ', ' order by c.relname) as table_names
from pg_class c where c.relnamespace = 'retailos'::regnamespace and c.relkind in ('r','p')
group by c.xmin::text order by min(c.oid)`;
const MARKER_SQL = `select app, schema_version, migration_set from retailos.schema_info`;

if (process.argv.includes("--emit-sql")) {
  mkdirSync(diagDir, { recursive: true });
  const sql = `-- READ-ONLY diagnostic for the RetailOS migrations. GENERATED by scripts/hosted-diagnose.mjs --emit-sql from the 16 migration files.
-- It only SELECTs from the system catalogue and counts rows of seeded tables. It creates, alters, drops and deletes NOTHING, applies
-- NOTHING and does not touch the fresh-project guard. Safe to paste into the Supabase SQL editor. Run each numbered block ONE AT A TIME
-- (the editor shows only the last result). Paste the results back; they contain object names and counts only, no business data.
-- Migration ids are the first 14 digits of each file name (20261010100000 ... 20261010100015).

-- ===== 1. Which schemas exist =====
select nspname as schema from pg_namespace where nspname in ('retailos', 'retailos_private') order by 1;

-- ===== 2. Supabase's own migration history, if any (the RetailOS scripts do not write to it) =====
${HISTORY_SQL};
-- If true, also run:  select * from supabase_migrations.schema_migrations order by 1;

-- ===== 3. PER-MIGRATION VERDICT: expected objects vs what exists =====
-- present = expected_objects  -> that migration's objects are all there
-- present = 0                 -> none of them are there
-- anything in between         -> PARTIAL; first_missing names what is absent
-- Migration 20261010100000 (the guard) creates nothing, so it can never be confirmed from the catalogue.
${summarySql(objs)};

-- ===== 4. Every expected object that is missing (full list) =====
select mig, kind, sch, tbl, name from (
${diagnosticSql(objs)}
) d where not present order by mig, kind, sch, tbl, name;

-- ===== 5. Function definitions: is the INSTALLED text the same as a fully migrated database? =====
-- (CREATE OR REPLACE in later migrations means a function can exist in an older version.) No rows = every function matches.
${functionCompareSql(hashLines)};

-- ===== 6. Were the tables created in one transaction or several? (each distinct value = one transaction) =====
${XMIN_SQL};

-- ===== 7. The write-once schema marker (created ONLY by migration 20261010100015) =====
-- If this errors with 'relation does not exist', migration ...015 has not run.
${MARKER_SQL};

-- ===== 8. Is another session running right now? (stop and wait if > 0) =====
select count(*) as other_active_sessions from pg_stat_activity
where datname = current_database() and pid <> pg_backend_pid() and state = 'active' and backend_type = 'client backend';

-- ===== 9. Full structure comparison =====
-- Run supabase/retailos/verify/inventory.sql, save the output as inventory-actual.txt, then:
--   npm run retailos:verify:schema -- inventory-actual.txt
-- It lists exactly which lines of the approved 1013-line inventory are MISSING or UNEXPECTED.
`;
  writeFileSync(join(diagDir, "diagnose.sql"), sql);
  console.log(`Wrote supabase/retailos/diagnostics/diagnose.sql (${objs.length} expected objects across ${new Set(objs.map((o) => o.mig)).size} migrations).`);
  process.exit(0);
}

// ---- run against the database -------------------------------------------------------------------------------------------
const env = { ...process.env };
const envFile = join(root, ".env.local");
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && m[2] !== "" && env[m[1]] === undefined) env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2");
  }
}
const ref = env.RETAILOS_SUPABASE_PROJECT_REF ?? "";
const dbUrl = env.RETAILOS_DATABASE_URL ?? "";
const die = (m) => {
  console.error("ABORT: " + m);
  process.exit(1);
};
if (!/^[a-z0-9]{20}$/.test(ref) || !dbUrl) die("RETAILOS_SUPABASE_PROJECT_REF and RETAILOS_DATABASE_URL are required");
const u = new URL(dbUrl);
if (!(u.hostname.includes(ref) || decodeURIComponent(u.username).endsWith("." + ref))) die("connection string does not carry the expected project ref");

const client = new pg.Client({
  connectionString: dbUrl,
  ssl: { rejectUnauthorized: true, ...(env.RETAILOS_DB_CA_FILE ? { ca: readFileSync(env.RETAILOS_DB_CA_FILE, "utf8") } : {}) },
  connectionTimeoutMillis: 20000,
  statement_timeout: 60000,
});
try {
  await client.connect();
} catch (e) {
  die("database connection failed: " + String(e.message).split(dbUrl).join("<url>"));
}
const q = async (sql) => (await client.query(sql)).rows;
try {
  await client.query("begin read only");
  const who = (await q("select current_user u, current_setting('server_version_num')::int v"))[0];
  console.log(`connected: user=${who.u} server_version_num=${who.v}   (read-only transaction; rolled back at the end)`);
  const schemas = (await q("select nspname from pg_namespace where nspname in ('retailos','retailos_private') order by 1")).map((r) => r.nspname);
  console.log(`schemas present: ${schemas.join(", ") || "none"}`);
  const hist = (await q(HISTORY_SQL))[0].history_table_exists;
  console.log(`supabase_migrations.schema_migrations exists: ${hist}`);
  if (hist) console.log("  versions recorded: " + ((await q("select version from supabase_migrations.schema_migrations order by 1")).map((r) => r.version).join(", ") || "(none)"));
  console.log(`other active sessions: ${(await q("select count(*)::int n from pg_stat_activity where datname = current_database() and pid <> pg_backend_pid() and state = 'active' and backend_type = 'client backend'"))[0].n}`);

  console.log("\n== PER-MIGRATION VERDICT (derived from each migration's own SQL, checked against the live catalogue) ==");
  const rows = await q(diagnosticSql(objs));
  const v = verdicts(rows, migs);
  const names = Object.fromEntries(migFiles.map((f) => [f.slice(0, 14), f]));
  for (const x of v) {
    console.log(`${x.mig}  ${String(x.present).padStart(3)}/${String(x.total).padEnd(3)}  ${x.status}\n    ${names[x.mig]}`);
    if (x.missing.length && x.present < x.total) console.log(`    missing (${x.missing.length}): ${x.missing.slice(0, 8).join("; ")}${x.missing.length > 8 ? " …" : ""}`);
  }

  console.log("\n== FUNCTION DEFINITIONS vs a fully migrated local database ==");
  const diff = await q(functionCompareSql(hashLines));
  const last = lastDefiningMigration(objs);
  if (!diff.length) console.log("every installed function matches the approved definition");
  for (const d of diff.slice(0, 40)) {
    const name = d.function.replace(/\(.*$/, "").replace(/^"?([^".]+)"?\."?([^".]+)"?$/, "$1.$2");
    console.log(`${d.status.padEnd(20)} ${d.function}   (last defined by migration ${last.get(name) ?? "?"})`);
  }
  if (diff.length > 40) console.log(`… and ${diff.length - 40} more`);

  console.log("\n== SCHEMA MARKER (only migration 20261010100015 creates it) ==");
  try {
    await client.query("savepoint s");
    console.log(JSON.stringify((await q(MARKER_SQL))));
  } catch (e) {
    await client.query("rollback to savepoint s");
    console.log(`not readable (${e.code}): ${e.code === "42P01" ? "retailos.schema_info does not exist" : e.message}`);
  }

  console.log("\n== TABLE CREATION TRANSACTIONS (distinct values = distinct transactions; one value = applied as one script) ==");
  for (const r of await q(XMIN_SQL)) console.log(`tx ${r.creating_transaction}: ${r.tables} table(s): ${String(r.table_names).slice(0, 160)}${String(r.table_names).length > 160 ? " …" : ""}`);

  console.log("\n== FULL INVENTORY vs approved expected_inventory.txt ==");
  const actual = (await q(readFileSync(join(root, "supabase", "retailos", "verify", "inventory.sql"), "utf8"))).map((r) => r.l);
  const expected = readFileSync(join(root, "supabase", "retailos", "verify", "expected_inventory.txt"), "utf8").trim().split("\n");
  const miss = expected.filter((l) => !actual.includes(l));
  const unexp = actual.filter((l) => !expected.includes(l));
  const kind = (l) => l.split("|")[0];
  const tally = (a) => Object.entries(a.reduce((m, l) => ({ ...m, [kind(l)]: (m[kind(l)] ?? 0) + 1 }), {})).map(([k, n]) => `${k}:${n}`).join(" ");
  console.log(`actual ${actual.length} lines vs expected ${expected.length}: ${miss.length} missing [${tally(miss)}], ${unexp.length} unexpected [${tally(unexp)}]`);
  for (const l of miss.slice(0, 12)) console.log("  MISSING     " + l.slice(0, 140));
  for (const l of unexp.slice(0, 12)) console.log("  UNEXPECTED  " + l.slice(0, 140));
} finally {
  await client.query("rollback").catch(() => {});
  await client.end().catch(() => {});
}
console.log("\nDONE. Read-only: nothing was applied, created, altered, dropped or recorded.");
