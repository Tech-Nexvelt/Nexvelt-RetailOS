// Mechanical port of the tested migrations from schema `public`/`private` to `retailos`/`retailos_private`,
// plus the three deliberate safety edits. Source dir is never modified.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
const root = join(import.meta.dirname, "..");
const src = join(root, "supabase", "migrations");
const out = join(root, "supabase", "retailos", "migrations");
mkdirSync(out, { recursive: true });
const mech = (s) =>
  s.replace(/\bpublic\./g, "retailos.").replace(/\bprivate\./g, "retailos_private.")
   .replace(/schema private\b/g, "schema retailos_private")
   .replace(/schema public\b/g, "schema retailos")
   .replace(/schema if not exists private\b/g, "schema if not exists retailos_private");
const header = (f) =>
  `-- RETAILOS-SCHEMA PORT of supabase/migrations/${f}. GENERATED by scripts/port-to-retailos.mjs; sealed in SHA256SUMS.
-- Targets schemas retailos and retailos_private ONLY. Never touches schema public (Tirumala) or the live retailos_* tables.
-- Not applied to any database yet. See docs/RETAILOS_PRODUCTION_PREFLIGHT.md before running anything.

`;
const must = (cond, msg) => { if (!cond) throw new Error("port: " + msg); };
for (const f of readdirSync(src).filter((n) => n.endsWith(".sql")).sort()) {
  let s = mech(readFileSync(join(src, f), "utf8"));
  if (f.startsWith("20261010100001")) {
    const a = s.indexOf("alter default privileges revoke execute");
    must(a > 0, "foundation anchor");
    const b = s.indexOf("create or replace function retailos_private.set_updated_at");
    must(b > a, "foundation anchor 2");
    s = s.slice(0, a) + `-- NOT done here (it would be project-wide and affect Tirumala): a GLOBAL "alter default privileges
-- revoke execute on functions from public". Instead every function in this design is revoked from
-- PUBLIC/anon explicitly, and tests/db/isolation.test.ts fails if one is missed.
-- Default privileges are changed only for schema retailos, for new objects created by the migration role.
alter default privileges in schema retailos revoke all on tables from anon, authenticated;
alter default privileges in schema retailos revoke all on sequences from anon, authenticated;
alter default privileges in schema retailos revoke all on functions from anon, authenticated;
grant usage on schema retailos to authenticated, service_role;

` + s.slice(b);
    must(s.includes("create schema if not exists retailos_private;"), "foundation schema anchor");
    s = s.replace("create schema if not exists retailos_private;", "create schema if not exists retailos;\ncreate schema if not exists retailos_private;");
  }
  if (f.startsWith("20261010100002")) {
    const a = s.indexOf("create or replace function retailos_private.handle_new_user()");
    const b = s.indexOf("create table retailos.platform_admins");
    must(a > 0 && b > a, "tenancy anchors");
    s = s.slice(0, a) + `-- Tirumala's own trigger on auth.users (trg_on_auth_user_created) is NOT touched and RetailOS adds no
-- trigger there. A RetailOS profile is created on demand, only when someone is given a RetailOS
-- membership, so a Tirumala-only user never gets a RetailOS row.
create or replace function retailos_private.ensure_profile(p_user uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into retailos.profiles (id, full_name)
  select u.id, left(coalesce(u.raw_user_meta_data ->> 'full_name', ''), 120)
  from auth.users u where u.id = p_user
  on conflict (id) do nothing;
end;
$$;

` + s.slice(b);
  }
  if (f.startsWith("20261010100003")) {
    must(s.includes("revoke all on all tables in schema retailos from anon, authenticated;"), "authz revoke anchor");
    s = s.replace("revoke all on all tables in schema retailos from anon, authenticated;",
      `-- Scoped to this design's own tables. Never "all tables in schema": the 10 live retailos_* tables
-- must keep their current grants until a separate, approved decision.
revoke all on retailos.permissions, retailos.roles, retailos.role_permissions, retailos.tenants,
  retailos.tenant_settings, retailos.branches, retailos.counters, retailos.profiles,
  retailos.platform_admins, retailos.tenant_memberships, retailos.branch_memberships,
  retailos.permission_overrides, retailos.role_discount_limits from anon, authenticated;`);
  }
  if (f.startsWith("20261010100005")) {
    for (const v of ["p_owner_user", "p_user"]) {
      const a = `  if not exists (select 1 from retailos.profiles where id = ${v} and status = 'ACTIVE') then`;
      must(s.includes(a), "profile check " + v);
      s = s.replace(a, `  perform retailos_private.ensure_profile(${v});
` + a);
    }
  }
  writeFileSync(join(out, f), header(f) + s);
}
console.log("ported");

